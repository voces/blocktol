// Bakes the build's git SHA into common/version.ts, the one source both sides
// read: the server (beginLogger/endLogger) stamps its build with it and the
// client bundles it to know which build it is. Run by `npm run build` and
// `npm run dev`; the file is gitignored. One shared string means server and
// client values are identical by construction, with no short-vs-full mismatch
// to make clients look stale.
//
// Uses the GIT_SHA env if set (builds that have it but no git), else the
// working tree's short SHA, else "dev" (an unbuilt checkout), where the version
// machinery no-ops (see noteServerVersion). As a build artifact like public/js,
// `npm start` requires a prior build.
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import process from "node:process";

const gitSha = (): string => {
  const fromEnv = process.env.GIT_SHA;
  if (fromEnv) return fromEnv;
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch { /* git unavailable, or not a checkout */ }
  return "dev";
};

const sha = gitSha();
await writeFile(
  new URL("../common/version.ts", import.meta.url),
  `// GENERATED by scripts/genVersion.ts at build time — do not edit or commit.\n` +
    // `: string` widens the baked literal; otherwise the type check narrows SHA
    // to e.g. "8e7f80d" and flags the `=== "dev"` guards as impossible.
    `export const SHA: string = ${JSON.stringify(sha)};\n`,
);
console.log(`build version: ${sha}`);
